import 'dart:convert';
import 'package:flutter/foundation.dart';
import 'package:http/http.dart' as http;
import '../constants/vault_config.dart';
import '../database/database_helper.dart';

/// Service managing two-way synchronization between local SQLite database
/// and Supabase (Cloud PostgreSQL) using direct REST PostgREST protocol.
/// Fulfills Slide Requirement: "Terkoneksi database / penyimpanan lokal dan online"
class SupabaseService {
  SupabaseService._();
  static final SupabaseService instance = SupabaseService._();

  DateTime? _lastSyncTime;
  DateTime? get lastSyncTime => _lastSyncTime;

  /// SQL script to initialize the PostgreSQL table in Supabase SQL Editor
  static const String sqlTableSchema = '''
-- Create vault_items table in Supabase PostgreSQL
CREATE TABLE IF NOT EXISTS vault_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL DEFAULT 'azzaky',
    name TEXT NOT NULL,
    category TEXT,
    purchase_price NUMERIC,
    current_valuation NUMERIC,
    purchase_date TEXT,
    warranty_expiry_date TEXT,
    serial_number TEXT UNIQUE,
    blockchain_hash TEXT,
    image_url TEXT,
    is_collectible INTEGER DEFAULT 0,
    synced_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Enable Row Level Security (RLS) & Public Access Policy for Demo
ALTER TABLE vault_items ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all for demo" ON vault_items;
CREATE POLICY "Allow all for demo" ON vault_items
    FOR ALL
    USING (true)
    WITH CHECK (true);
''';

  Map<String, String> _headers() {
    final key = VaultConfig.supabaseAnonKey;
    return {
      'apikey': key,
      'Authorization': 'Bearer $key',
      'Content-Type': 'application/json',
      'Prefer': 'resolution=merge-duplicates,return=representation',
    };
  }

  /// Push all local items from SQLite to Supabase PostgreSQL table
  Future<Map<String, dynamic>> syncToCloud() async {
    final hasConfig = VaultConfig.hasSupabase;
    final localItems = await DatabaseHelper.instance.getItems();

    if (localItems.isEmpty) {
      return {
        'success': true,
        'count': 0,
        'message': 'No local SQLite assets found to synchronize.',
        'isLive': hasConfig,
      };
    }

    if (!hasConfig) {
      // Offline / unconfigured simulation mode
      _lastSyncTime = DateTime.now();
      return {
        'success': true,
        'count': localItems.length,
        'message': 'Simulated cloud sync for ${localItems.length} assets (Add SUPABASE_URL in .env for live sync).',
        'isLive': false,
      };
    }

    try {
      final endpoint = Uri.parse('${VaultConfig.supabaseUrl}/rest/v1/vault_items');
      final payload = localItems.map((item) {
        return {
          'user_id': 'azzaky',
          'name': item['name'],
          'category': item['category'],
          'purchase_price': item['purchase_price'],
          'current_valuation': item['current_valuation'],
          'purchase_date': item['purchase_date'],
          'warranty_expiry_date': item['warranty_expiry_date'],
          'serial_number': item['serial_number'] ?? 'SN-${DateTime.now().millisecondsSinceEpoch}',
          'blockchain_hash': item['blockchain_hash'],
          'image_url': item['image_url'],
          'is_collectible': item['is_collectible'] ?? 0,
        };
      }).toList();

      final response = await http
          .post(
            endpoint,
            headers: _headers(),
            body: jsonEncode(payload),
          )
          .timeout(const Duration(seconds: 10));

      if (response.statusCode == 200 || response.statusCode == 201) {
        _lastSyncTime = DateTime.now();
        return {
          'success': true,
          'count': localItems.length,
          'message': 'Successfully synced ${localItems.length} assets to Supabase PostgreSQL!',
          'isLive': true,
        };
      } else {
        debugPrint('[Supabase] Sync error response: ${response.statusCode} - ${response.body}');
        return {
          'success': false,
          'count': 0,
          'message': 'Supabase responded with code ${response.statusCode}: ${response.body}',
          'isLive': true,
        };
      }
    } catch (e) {
      debugPrint('[Supabase] Sync exception: $e');
      return {
        'success': false,
        'count': 0,
        'message': 'Connection error during cloud sync: $e',
        'isLive': true,
      };
    }
  }

  /// Pull all assets from Supabase PostgreSQL table and merge into local SQLite
  Future<Map<String, dynamic>> restoreFromCloud() async {
    final hasConfig = VaultConfig.hasSupabase;

    if (!hasConfig) {
      return {
        'success': true,
        'count': 0,
        'message': 'Configure SUPABASE_URL in .env to pull live PostgreSQL data.',
        'isLive': false,
      };
    }

    try {
      final endpoint = Uri.parse('${VaultConfig.supabaseUrl}/rest/v1/vault_items?select=*');
      final response = await http
          .get(endpoint, headers: _headers())
          .timeout(const Duration(seconds: 10));

      if (response.statusCode == 200) {
        final List<dynamic> cloudItems = jsonDecode(response.body);
        int inserted = 0;

        for (final item in cloudItems) {
          final map = {
            'name': item['name'],
            'category': item['category'],
            'purchase_price': (item['purchase_price'] as num?)?.toDouble() ?? 0.0,
            'current_valuation': (item['current_valuation'] as num?)?.toDouble() ?? 0.0,
            'purchase_date': item['purchase_date'],
            'warranty_expiry_date': item['warranty_expiry_date'],
            'serial_number': item['serial_number'],
            'blockchain_hash': item['blockchain_hash'],
            'image_url': item['image_url'],
            'is_collectible': item['is_collectible'] ?? 0,
          };
          try {
            await DatabaseHelper.instance.insertItem(map);
            inserted++;
          } catch (_) {}
        }

        _lastSyncTime = DateTime.now();
        return {
          'success': true,
          'count': inserted,
          'message': 'Restored $inserted assets from Supabase PostgreSQL to SQLite!',
          'isLive': true,
        };
      } else {
        return {
          'success': false,
          'count': 0,
          'message': 'Supabase pull failed: ${response.statusCode}',
          'isLive': true,
        };
      }
    } catch (e) {
      return {
        'success': false,
        'count': 0,
        'message': 'Failed connecting to Supabase: $e',
        'isLive': true,
      };
    }
  }
}
