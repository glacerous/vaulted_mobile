  Map<String, String> _headers() {
    final key = VaultConfig.supabaseAnonKey;
    return {
      'apikey': key,
      'Authorization': 'Bearer $key',
      'Content-Type': 'application/json',
      'Prefer': 'resolution=merge-duplicates,return=representation',
    };
  }

  /// Register a user in Supabase PostgreSQL (vault_users)
  Future<Map<String, dynamic>> registerUserOnline({
    required String username,
    required String passwordHash,
    required String fullName,
  }) async {
    if (!VaultConfig.hasSupabase) {
      return {'success': false, 'message': 'Supabase not configured'};
    }
    try {
      final endpoint = Uri.parse('${VaultConfig.supabaseUrl}/rest/v1/vault_users');
      final payload = {
        'username': username.trim().toLowerCase(),
        'password_hash': passwordHash,
        'full_name': fullName.trim(),
      };
      final response = await http
          .post(
            endpoint,
            headers: _headers(),
            body: jsonEncode(payload),
          )
          .timeout(const Duration(seconds: 6));

      if (response.statusCode == 201 || response.statusCode == 200) {
        return {'success': true, 'message': 'Registered successfully in online DB'};
      } else if (response.statusCode == 409) {
        return {'success': false, 'isDuplicate': true, 'message': 'Username is already registered online.'};
      } else {
        debugPrint('[Supabase] registerUserOnline notice: ${response.statusCode} - ${response.body}');
        return {'success': false, 'message': 'Online DB returned ${response.statusCode}'};
      }
    } catch (e) {
      debugPrint('[Supabase] registerUserOnline exception: $e');
      return {'success': false, 'message': e.toString()};
    }
  }

  /// Authenticate user against Supabase PostgreSQL (vault_users)
  Future<Map<String, dynamic>?> authenticateUserOnline({
    required String username,
    required String passwordHash,
  }) async {
    if (!VaultConfig.hasSupabase) return null;
    try {
      final cleanUser = username.trim().toLowerCase();
      final endpoint = Uri.parse(
        '${VaultConfig.supabaseUrl}/rest/v1/vault_users?username=eq.$cleanUser&password_hash=eq.$passwordHash&select=*',
      );
      final response = await http
          .get(endpoint, headers: _headers())
          .timeout(const Duration(seconds: 6));

      if (response.statusCode == 200) {
        final List<dynamic> list = jsonDecode(response.body);
        if (list.isNotEmpty) {
          return Map<String, dynamic>.from(list.first);
        }
      }
    } catch (e) {
      debugPrint('[Supabase] authenticateUserOnline exception: $e');
    }
    return null;
  }

  /// Push all local items from SQLite to Supabase PostgreSQL table
  Future<Map<String, dynamic>> syncToCloud() async {
    final hasConfig = VaultConfig.hasSupabase;
    final activeUser = AuthService.instance.activeSessionUser ?? 'azzaky';
    final localItems = await DatabaseHelper.instance.getItems(activeUser);

    if (localItems.isEmpty) {
      return {
        'success': true,
        'count': 0,
        'message': 'No local SQLite assets found to synchronize for @$activeUser.',
        'isLive': hasConfig,
      };
    }

    if (!hasConfig) {
      // Offline / unconfigured simulation mode
      _lastSyncTime = DateTime.now();
      return {
        'success': true,
        'count': localItems.length,
        'message': 'Simulated cloud sync for ${localItems.length} assets (Add SUPABASE_URL in .env for live sync).',
        'isLive': false,
      };
    }

    try {
      final endpoint = Uri.parse('${VaultConfig.supabaseUrl}/rest/v1/vault_items');
      final payload = localItems.map((item) {
        return {
          'user_id': (item['user_id'] as String?)?.isNotEmpty == true
              ? item['user_id']
              : activeUser,
          'name': item['name'],
          'category': item['category'],
          'purchase_price': item['purchase_price'],
          'current_valuation': item['current_valuation'],
          'purchase_date': item['purchase_date'],
          'warranty_expiry_date': item['warranty_expiry_date'],
          'serial_number': item['serial_number'],
          'blockchain_hash': item['blockchain_hash'],
          'image_url': item['image_url'],
          'is_collectible': item['is_collectible'] ?? 0,
        };
      }).toList();

      final response = await http
          .post(
            endpoint,
            headers: _headers(),
            body: jsonEncode(payload),
          )
          .timeout(const Duration(seconds: 10));

      if (response.statusCode == 200 || response.statusCode == 201) {
        _lastSyncTime = DateTime.now();
        return {
          'success': true,
          'count': localItems.length,
          'message': 'Successfully synced ${localItems.length} assets to Supabase PostgreSQL!',
          'isLive': true,
        };
      } else {
        debugPrint('[Supabase] Sync error response: ${response.statusCode} - ${response.body}');
        return {
          'success': false,
          'count': 0,
          'message': 'Supabase responded with code ${response.statusCode}: ${response.body}',
          'isLive': true,
        };
      }
    } catch (e) {
      debugPrint('[Supabase] Sync exception: $e');
      return {
        'success': false,
        'count': 0,
        'message': 'Connection error during cloud sync: $e',
        'isLive': true,
      };
    }
  }

  /// Pull all assets from Supabase PostgreSQL table and merge into local SQLite
  Future<Map<String, dynamic>> restoreFromCloud() async {
    final hasConfig = VaultConfig.hasSupabase;

    if (!hasConfig) {
      return {
        'success': true,
        'count': 0,
        'message': 'Configure SUPABASE_URL in .env to pull live PostgreSQL data.',
        'isLive': false,
      };
    }

    try {
      final activeUser = AuthService.instance.activeSessionUser ?? 'azzaky';
      final endpoint = Uri.parse(
        '${VaultConfig.supabaseUrl}/rest/v1/vault_items?user_id=eq.$activeUser&select=*',
      );
      final response = await http
          .get(endpoint, headers: _headers())
          .timeout(const Duration(seconds: 10));

      if (response.statusCode == 200) {
        final List<dynamic> cloudItems = jsonDecode(response.body);
        int inserted = 0;

        for (final item in cloudItems) {
          final map = {
            'user_id': item['user_id'] ?? activeUser,
            'name': item['name'],
            'category': item['category'],
            'purchase_price': (item['purchase_price'] as num?)?.toDouble() ?? 0.0,
            'current_valuation': (item['current_valuation'] as num?)?.toDouble() ?? 0.0,
            'purchase_date': item['purchase_date'],
            'warranty_expiry_date': item['warranty_expiry_date'],
            'serial_number': item['serial_number'],
            'blockchain_hash': item['blockchain_hash'],
            'image_url': item['image_url'],
            'is_collectible': item['is_collectible'] ?? 0,
          };
          try {
            await DatabaseHelper.instance.insertItem(map, pushToCloud: false);
            inserted++;
          } catch (_) {}
        }

        _lastSyncTime = DateTime.now();
        return {
          'success': true,
          'count': inserted,
          'message': 'Restored $inserted assets from Supabase PostgreSQL to SQLite!',
          'isLive': true,
        };
      } else {
        return {
          'success': false,
          'count': 0,
          'message': 'Supabase pull failed: ${response.statusCode}',
          'isLive': true,
        };
      }
    } catch (e) {
      return {
        'success': false,
        'count': 0,
        'message': 'Failed connecting to Supabase: $e',
        'isLive': true,
      };
    }
  }

  bool _isAutoSyncing = false;

  /// Two-way delta sync between local SQLite and Supabase PostgreSQL.
  /// Merges new assets from cloud into local SQLite without duplicates,
  /// and pushes new local assets to cloud.
  Future<Map<String, dynamic>> syncTwoWay() async {
    if (!VaultConfig.hasSupabase) {
      return {
        'success': false,
        'pulled': 0,
        'pushed': 0,
        'message': 'Supabase not configured in .env',
      };
    }

    try {
      final activeUser = AuthService.instance.activeSessionUser ?? 'azzaky';
      final localItems = await DatabaseHelper.instance.getItems(activeUser);

      final endpoint = Uri.parse(
        '${VaultConfig.supabaseUrl}/rest/v1/vault_items?user_id=eq.$activeUser&select=*',
      );
      final response = await http
          .get(endpoint, headers: _headers())
          .timeout(const Duration(seconds: 10));

      if (response.statusCode != 200) {
        return {
          'success': false,
          'pulled': 0,
          'pushed': 0,
          'message': 'Failed to reach Supabase: ${response.statusCode}',
        };
      }

      final List<dynamic> cloudItems = jsonDecode(response.body);
      int pulledCount = 0;
      int pushedCount = 0;

      // 1. Pull: Find items in Cloud that do NOT exist in Local SQLite
      for (final rawCloud in cloudItems) {
        if (rawCloud is! Map) continue;
        final cloudItem = Map<String, dynamic>.from(rawCloud);

        final alreadyExists = localItems.any((local) => _isSameItem(local, cloudItem));
        if (!alreadyExists) {
          final toInsert = {
            'user_id': cloudItem['user_id'] ?? activeUser,
            'name': cloudItem['name'],
            'category': cloudItem['category'],
            'purchase_price': (cloudItem['purchase_price'] as num?)?.toDouble() ?? 0.0,
            'current_valuation': (cloudItem['current_valuation'] as num?)?.toDouble() ?? 0.0,
            'purchase_date': cloudItem['purchase_date'],
            'warranty_expiry_date': cloudItem['warranty_expiry_date'],
            'serial_number': cloudItem['serial_number'],
            'blockchain_hash': cloudItem['blockchain_hash'],
            'image_url': cloudItem['image_url'],
            'is_collectible': cloudItem['is_collectible'] ?? 0,
          };
          try {
            await DatabaseHelper.instance.insertItem(toInsert, pushToCloud: false);
            pulledCount++;
          } catch (e) {
            debugPrint('[SupabaseService] Error inserting pulled item: $e');
          }
        }
      }

      // 2. Push: Find items in Local SQLite that do NOT exist in Cloud
      for (final localItem in localItems) {
        final existsInCloud = cloudItems.any((c) {
          if (c is! Map) return false;
          return _isSameItem(localItem, Map<String, dynamic>.from(c));
        });

        if (!existsInCloud) {
          try {
            await pushSingleItemOnline(localItem);
            pushedCount++;
          } catch (e) {
            debugPrint('[SupabaseService] Error pushing delta item: $e');
          }
        }
      }

      _lastSyncTime = DateTime.now();
      return {
        'success': true,
        'pulled': pulledCount,
        'pushed': pushedCount,
        'message': 'Synced: $pulledCount pulled from cloud, $pushedCount pushed to cloud.',
      };
    } catch (e) {
      debugPrint('[SupabaseService] syncTwoWay notice: $e');
      return {
        'success': false,
        'pulled': 0,
        'pushed': 0,
        'message': 'Sync notice: $e',
      };
    }
  }

  bool _isSameItem(Map<String, dynamic> a, Map<String, dynamic> b) {
    final aHash = a['blockchain_hash']?.toString().trim();
    final bHash = b['blockchain_hash']?.toString().trim();
    if (aHash != null && aHash.isNotEmpty && bHash != null && bHash.isNotEmpty) {
      if (aHash == bHash) return true;
    }

    final aSn = a['serial_number']?.toString().trim();
    final bSn = b['serial_number']?.toString().trim();
    if (aSn != null && aSn.isNotEmpty && bSn != null && bSn.isNotEmpty) {
      if (aSn == bSn) return true;
    }

    final aName = a['name']?.toString().trim().toLowerCase();
    final bName = b['name']?.toString().trim().toLowerCase();
    final aDate = a['purchase_date']?.toString().trim();
    final bDate = b['purchase_date']?.toString().trim();
    final aCat = a['category']?.toString().trim().toLowerCase();
    final bCat = b['category']?.toString().trim().toLowerCase();

    return aName == bName && aDate == bDate && aCat == bCat;
  }

  /// Silently keeps local SQLite and Supabase PostgreSQL in sync in the background
  Future<Map<String, dynamic>> autoSyncInBackground() async {
    if (!VaultConfig.hasSupabase || _isAutoSyncing) {
      return {'pulled': 0, 'pushed': 0};
    }
    _isAutoSyncing = true;
    try {
      return await syncTwoWay();
    } catch (e) {
      debugPrint('[SupabaseService] autoSyncInBackground notice: $e');
      return {'pulled': 0, 'pushed': 0};
    } finally {
      _isAutoSyncing = false;
    }
  }

  /// Push a single item to Supabase PostgreSQL immediately in the background
  Future<void> pushSingleItemOnline(Map<String, dynamic> item) async {
    if (!VaultConfig.hasSupabase) return;
    try {
      final activeUser = AuthService.instance.activeSessionUser ?? 'azzaky';
      final endpoint = Uri.parse('${VaultConfig.supabaseUrl}/rest/v1/vault_items');
      final payload = [
        {
          'user_id': (item['user_id'] as String?)?.isNotEmpty == true
              ? item['user_id']
              : activeUser,
          'name': item['name'],
          'category': item['category'],
          'purchase_price': item['purchase_price'],
          'current_valuation': item['current_valuation'],
          'purchase_date': item['purchase_date'],
          'warranty_expiry_date': item['warranty_expiry_date'],
          'serial_number': item['serial_number'],
          'blockchain_hash': item['blockchain_hash'],
          'image_url': item['image_url'],
          'is_collectible': item['is_collectible'] ?? 0,
        }
      ];
      await http
          .post(
            endpoint,
            headers: _headers(),
            body: jsonEncode(payload),
          )
          .timeout(const Duration(seconds: 6));
    } catch (e) {
      debugPrint('[SupabaseService] pushSingleItemOnline notice: $e');
    }
  }
}
