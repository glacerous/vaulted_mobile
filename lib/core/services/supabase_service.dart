/// Service managing two-way synchronization between local SQLite database
/// and Supabase (Cloud PostgreSQL) using direct REST PostgREST protocol.
/// Fulfills Slide Requirement: "Terkoneksi database / penyimpanan lokal dan online"
class SupabaseService {
  SupabaseService._();
  static final SupabaseService instance = SupabaseService._();

  DateTime? _lastSyncTime;
  DateTime? get lastSyncTime => _lastSyncTime;

